-- Associative graph of the norms (NG_CMP_ASSOC): rows per kind and structure. Read only; every check row must be 0.
SELECT 'edges ' || e.EDGE_TYPE_ENUM_ID AS check_name, COUNT(*) AS n FROM GRAPH_EDGE e WHERE e.GRAPH_ID = 'NG_CMP_ASSOC' GROUP BY e.EDGE_TYPE_ENUM_ID
UNION ALL
SELECT 'vertices', COUNT(*) FROM GRAPH_VERTEX v WHERE v.GRAPH_ID = 'NG_CMP_ASSOC'
UNION ALL
SELECT 'check: vertices without their AgreementItem', COUNT(*) FROM GRAPH_VERTEX v
  LEFT JOIN AGREEMENT_ITEM i ON i.AGREEMENT_ID = v.AGREEMENT_ID AND i.AGREEMENT_ITEM_SEQ_ID = v.AGREEMENT_ITEM_SEQ_ID
 WHERE v.GRAPH_ID = 'NG_CMP_ASSOC' AND i.AGREEMENT_ID IS NULL
UNION ALL
SELECT 'check: edges without a vertex', COUNT(*) FROM GRAPH_EDGE e
  LEFT JOIN GRAPH_VERTEX f ON f.GRAPH_VERTEX_ID = e.FROM_VERTEX_ID LEFT JOIN GRAPH_VERTEX t ON t.GRAPH_VERTEX_ID = e.TO_VERTEX_ID
 WHERE e.GRAPH_ID = 'NG_CMP_ASSOC' AND (f.GRAPH_VERTEX_ID IS NULL OR t.GRAPH_VERTEX_ID IS NULL)
UNION ALL
SELECT 'check: edges without evidence', COUNT(*) FROM GRAPH_EDGE e
  LEFT JOIN PARAMETER p ON p.GRAPH_ID = e.GRAPH_ID AND p.GRAPH_EDGE_ID = e.GRAPH_EDGE_ID AND p.PARAMETER_DEF_ID = 'CmpAssocEvidence'
 WHERE e.GRAPH_ID = 'NG_CMP_ASSOC' AND p.PARAMETER_ID IS NULL
