"""Norm items: the partitions of a norm as they go into the mantle Agreement entities.

One Agreement per norm and language edition; one AgreementItem per partition down to the paragraph (capoverso),
point and sub-point, linked to its parent; canonical references written in the text become AgreementAssoc rows.
Conventions and decisions: cybersecurity/handoff/PLAN-NORMS-AGREEMENT.md (sections 2 and 3).
"""
import hashlib
import json
import os
import re
from dataclasses import dataclass, field
from xml.sax.saxutils import escape, quoteattr

ITEM_TYPES = {'AitPreamble', 'AitRecital', 'AitBook', 'AitTitle', 'AitChapter', 'AitSection', 'AitArticle',
              'AitParagraph', 'AitSubparagraph', 'AitPoint', 'AitSubPoint', 'AitAnnex', 'AitAnnexPart', 'AitNote',
              'AitExample', 'AitFigure', 'AitTable'}
ID_MAX = 40
SEQ_ID = re.compile(r'^[A-Za-z0-9_.\-]+$')


@dataclass
class ItemRef:
    """A citation written in the text of an item: to an item of the same or another norm, or to a document that is
    not in the knowledge base (`external` = its designator)."""
    raw: str
    toNormId: str = None
    toSeqId: str = None
    external: str = None


@dataclass
class Item:
    seqId: str
    parentSeqId: str
    type: str
    number: str = None
    title: dict = field(default_factory=dict)
    text: dict = field(default_factory=dict)
    sequence: int = 0
    source: str = ''
    term: dict = field(default_factory=dict)
    refs: list = field(default_factory=list)


def agreement_id(norm_id, lang):
    return f'{norm_id}-{lang.upper()}'


def stub_id(designator):
    """STUB-ISO-13857, STUB-EU-DIR-2006-42-EC: the Agreement of a cited document that is not loaded."""
    s = re.sub(r'\(EU\)|\(EC\)|\(EEC\)', '', designator)
    s = re.sub(r':\d{4}$', '', s.split(',')[0].strip())
    s = re.sub(r'\bRegulation\b', 'EU-REG', s)
    s = re.sub(r'\bDirective\b', 'EU-DIR', s)
    s = re.sub(r'\bDecision\b', 'EU-DEC', s)
    s = re.sub(r'\bNo\b', '', s)
    s = re.sub(r'[^A-Za-z0-9]+', '-', s).strip('-').upper()
    return ('STUB-' + s)[:ID_MAX]


def check_items(items, langs):
    """Structural errors of an item list (empty list = valid)."""
    errors = []
    ids = {}
    for it in items:
        if it.seqId in ids:
            errors.append(f'duplicate id {it.seqId}')
        ids[it.seqId] = it
        if len(it.seqId) > ID_MAX:
            errors.append(f'id longer than {ID_MAX}: {it.seqId}')
        if not SEQ_ID.match(it.seqId):
            errors.append(f'id with characters outside [A-Za-z0-9_.-]: {it.seqId!r}')
        if it.type not in ITEM_TYPES:
            errors.append(f'{it.seqId}: unknown type {it.type}')
    children = {}
    for it in items:
        if it.parentSeqId is not None and it.parentSeqId not in ids:
            errors.append(f'{it.seqId}: parent {it.parentSeqId} missing')
        children.setdefault(it.parentSeqId, []).append(it)
    for parent, kids in children.items():
        seqs = [k.sequence for k in kids]
        if len(set(seqs)) != len(seqs):
            errors.append(f'children of {parent}: repeated sequence numbers')
    for it in items:
        for lg in langs:
            if not (it.text.get(lg) or '').strip() and not (it.title.get(lg) or '').strip() \
                    and it.seqId not in children:
                errors.append(f'{it.seqId}: empty leaf in {lg}')
    return errors


def tree_text(items, lang):
    """Characters of the own texts and titles (whitespace collapsed), for the coverage check."""
    return sum(len(re.sub(r'\s+', ' ', (it.text.get(lang) or '') + ' ' + (it.title.get(lang) or '')).strip())
               for it in items)


def short_id(prefix, *parts):
    return prefix + hashlib.sha1('|'.join(p or '' for p in parts).encode('utf-8')).hexdigest()[:30]


HEADER = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by build_agreement.py (skill moqui-norm-loading) from {source}. Do not edit by hand: regenerate.
     {notice} -->
<entity-facade-xml type="seed">
'''


class AgreementWriter:
    """Seed XML of one language edition of a norm (Agreement, AgreementContent, AgreementItem, AgreementAssoc)."""

    def __init__(self, norm, lang, source, notice, editions):
        """norm: entry of config/norms.json; editions: normId -> list of loaded languages (targets of references)."""
        self.norm = norm
        self.lang = lang
        self.agreementId = agreement_id(norm['normId'], lang)
        self.source = source
        self.notice = notice
        self.editions = editions
        self.primary = editions.get(norm['normId'], [lang])[0] == lang

    def target_agreement(self, norm_id):
        langs = self.editions.get(norm_id)
        if not langs:
            return None
        return agreement_id(norm_id, self.lang if self.lang in langs else langs[0])

    def write(self, items, path, cross_path=None):
        """Seed of the edition at path; references to other loaded norms go to cross_path (loaded after all the
        editions: two norms that cite each other cannot be in each other's file because of the foreign keys)."""
        a = self.agreementId
        out = [HEADER.format(source=self.source, notice=self.notice)]
        attrs = {'agreementId': a, 'agreementTypeEnumId': self.norm.get('agreementType', 'AgrStandard'),
                 'description': self.norm['title'][:255], 'locale': self.lang}
        if self.norm.get('date'):
            attrs['agreementDate'] = self.norm['date'] + ' 00:00:00'
        out.append(row('mantle.party.agreement.Agreement', attrs))
        out.append(row('mantle.party.agreement.AgreementContent',
                       {'agreementContentId': short_id('ACN', a, self.source), 'agreementId': a,
                        'contentTypeEnumId': 'AcntDocument', 'contentLocation': self.source[:255],
                        'description': 'Source of the text'}))
        for other in self.editions.get(self.norm['normId'], []):
            if other != self.lang and other == self.editions[self.norm['normId']][0]:
                to = agreement_id(self.norm['normId'], other)
                out.append(row('mantle.party.agreement.AgreementAssoc',
                               {'agreementAssocId': short_id('AAS', a, None, to, None, 'translation'),
                                'agreementId': a, 'toAgreementId': to, 'agreementAssocTypeEnumId': 'AatTranslation'}))
        stubs = {}
        n_assoc = 0
        cross = []
        for it in items:
            f = {'agreementId': a, 'agreementItemSeqId': it.seqId, 'agreementItemTypeEnumId': it.type,
                 'sequenceNum': str(it.sequence)}
            if it.parentSeqId:
                f['parentItemSeqId'] = it.parentSeqId
            if it.number:
                f['itemNumber'] = it.number[:63]
            title = (it.title.get(self.lang) or '').strip()
            if title:
                f['itemTitle'] = title[:255]
            if it.source:
                f['sourceLocation'] = it.source[:255]
            text = (it.text.get(self.lang) or '').strip()
            out.append(row('mantle.party.agreement.AgreementItem', f, {'itemText': text} if text else None))
            # canonical references belong to the partition, not to the language: written once, in the primary
            # edition (the others are AatTranslation of it)
            for k, r in enumerate(it.refs if self.primary else [], 1):
                to_item = None
                if r.toNormId:
                    to = self.target_agreement(r.toNormId)
                    if to is None:
                        to = stub_id(r.toNormId)
                        stubs[to] = r.toNormId
                    elif r.toNormId == self.norm['normId']:
                        to = a
                    to_item = r.toSeqId if to.startswith(r.toNormId) else None
                else:
                    to = stub_id(r.external)
                    stubs[to] = r.external
                g = {'agreementAssocId': short_id('AAS', a, it.seqId, to, to_item, r.raw), 'agreementId': a,
                     'agreementItemSeqId': it.seqId, 'toAgreementId': to, 'agreementAssocTypeEnumId': 'AatReference',
                     'assocText': r.raw[:255], 'sequenceNum': str(k)}
                if to_item:
                    g['toAgreementItemSeqId'] = to_item
                (cross if cross_path and r.toNormId and r.toNormId != self.norm['normId'] and not
                 to.startswith('STUB-') else out).append(row('mantle.party.agreement.AgreementAssoc', g))
                n_assoc += 1
        out.append('</entity-facade-xml>\n')
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(''.join(out))
        if cross_path and cross:
            with open(cross_path, 'w', encoding='utf-8') as fh:
                fh.write(HEADER.format(source=self.source, notice='References to other norms of the knowledge base; '
                                       'loaded after all the 40_Norm files.') + ''.join(cross) + '</entity-facade-xml>\n')
        return {'items': len(items), 'assocs': n_assoc, 'crossRefs': len(cross), 'stubs': stubs}


def write_stubs(path, stubs, configured):
    """Union of the stub Agreements of all norms (file 41_NormStubs.xml); stubs of configured norms are dropped."""
    known = {}
    if os.path.exists(path):
        for m in re.finditer(r'agreementId="([^"]+)" agreementTypeEnumId="[^"]+" description="([^"]*)"',
                             open(path, encoding='utf-8').read()):
            known[m.group(1)] = m.group(2)
    for sid, designator in stubs.items():
        known[sid] = escape(designator, {'"': '&quot;'})
    out = [HEADER.format(source='the citations of the norms', notice='Stub Agreements: cited documents that are not '
                         'loaded (header only).')]
    for sid in sorted(known):
        if any(sid == f'STUB-{c}'.upper() for c in configured):
            continue
        typ = 'AgrLegislation' if re.search(r'\b(Regulation|Directive|Decision|Treaty)\b', known[sid]) else 'AgrStandard'
        out.append(f'    <mantle.party.agreement.Agreement agreementId="{sid}" agreementTypeEnumId="{typ}" '
                   f'description="{known[sid]}"/>\n')
    out.append('</entity-facade-xml>\n')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(''.join(out))
    return len(out) - 2


def row(entity, attrs, children=None):
    a = ' '.join(f'{k}={quoteattr(str(v))}' for k, v in attrs.items() if v is not None and v != '')
    if not children:
        return f'    <{entity} {a}/>\n'
    body = ''.join(f'<{k}>{escape(v)}</{k}>' for k, v in children.items())
    return f'    <{entity} {a}>{body}</{entity}>\n'


def write_items_jsonl(items, path):
    with open(path, 'w', encoding='utf-8') as fh:
        for it in items:
            d = dict(it.__dict__)
            d['refs'] = [r.__dict__ for r in it.refs]
            fh.write(json.dumps(d, ensure_ascii=False) + '\n')


def read_items_jsonl(path):
    out = []
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            d = json.loads(line)
            d['refs'] = [ItemRef(**r) for r in d['refs']]
            out.append(Item(**d))
    return out
